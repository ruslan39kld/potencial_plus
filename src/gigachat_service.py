    def _detect_combined_problems(self, message: str, history: list) -> list:
        """Определяет комбинированные проблемы из сообщения и истории"""
        problems = []
        message_lower = message.lower()
        history_text = " ".join([msg.get('content', '') for msg in history]).lower()

        if any(w in message_lower or w in history_text for w in ["долг", "кредит", "денег нет", "финанс"]):
            problems.append("долги")
        if any(w in message_lower or w in history_text for w in ["срочно", "быстро", "критично", "горит"]):
            problems.append("срочность")
        if any(w in message_lower or w in history_text for w in ["боюсь", "страшно", "не уверен", "тревож"]):
            problems.append("страхи")
        if any(w in message_lower or w in history_text for w in ["переез", "другой город", "релокац", "вахт"]):
            problems.append("переезд")
        if any(w in message_lower or w in history_text for w in ["смен", "другая профессия", "надоел", "хочу в"]):
            problems.append("смена_профессии")

        return problems

    async def gigachat_api_call(self, system_prompt: str, user_message: str, history: list) -> str:
        """Вызов GigaChat API с учётом истории диалога"""
        history_context = ""
        if history:
            recent = history[-6:]
            parts = []
            for msg in recent:
                role_label = "Пользователь" if msg.get("role") == "user" else "Ассистент"
                content = msg.get("content", "")[:300]
                parts.append(f"{role_label}: {content}")
            history_context = "\n\nИСТОРИЯ ДИАЛОГА:\n" + "\n".join(parts)

        full_prompt = system_prompt + history_context + f"\n\nПОЛЬЗОВАТЕЛЬ: {user_message}\n\nОТВЕТ:"

        with GigaChat(
            credentials=self.auth_key,
            scope=self.scope,
            model=self.model,
            verify_ssl_certs=False
        ) as giga:
            response = giga.chat(full_prompt)
            return response.choices[0].message.content

    async def get_context_aware_response(self, user_message: str, history: list, user_id: int) -> str:
        """Генерирует ответ с экспертным глубоким сопровождением"""
        async with self._semaphore:
            start_time = time.time()
            request_type = self.classify_request(user_message)
            dialog_level = len(history)

            logging.info(f"[GigaChat] context_aware: type={request_type}, level={dialog_level}, user={user_id}")

            system_prompt = self._build_deep_support_prompt(request_type, dialog_level, history)

            # Определяем комбинированные проблемы
            combined_problems = self._detect_combined_problems(user_message, history)
            if len(combined_problems) > 1:
                system_prompt += f"\n\n⚠️ КОМБИНИРОВАННАЯ СИТУАЦИЯ: {', '.join(combined_problems)}"
                system_prompt += "\n\nРаботай с ПРИОРИТЕТАМИ:"
                if "долги" in combined_problems and "срочность" in combined_problems:
                    system_prompt += "\n1. ПРИОРИТЕТ: Закрыть долги → вахта для быстрых денег"
                    system_prompt += "\n2. Остальные цели — ПОСЛЕ стабилизации финансов"
                if "страхи" in combined_problems:
                    system_prompt += "\n- ОБЯЗАТЕЛЬНО работай с психологическим барьером ПАРАЛЛЕЛЬНО"
                if "смена_профессии" in combined_problems and "долги" in combined_problems:
                    system_prompt += "\n- Смена профессии ПОСЛЕ формирования подушки (иначе риск)"

            try:
                response = await self.gigachat_api_call(system_prompt, user_message, history)

                if len(response) > 1000:
                    truncated = response[:950]
                    last_period = truncated.rfind('.')
                    if last_period > 500:
                        response = truncated[:last_period + 1]
                    else:
                        response = truncated.rsplit(' ', 1)[0] + '.'

                response = self.sanitize_markdown(response)
                ms = int((time.time() - start_time) * 1000)
                logging.info(f"[GigaChat] context_aware done: {len(response)} chars, {ms}ms")
                return response

            except Exception as e:
                logging.error(f"[GigaChat] get_context_aware_response error: {e}", exc_info=True)
                return self._fallback_response('career')